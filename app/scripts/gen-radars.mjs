/**
 * Bundles the merged radarbot corpus (preview/data/radars.json) into a typed
 * TS constant at src/data/radars.ts. Reads the corpus READ-ONLY — the source
 * of truth stays with the preview/tools agents; re-run after a merge refresh:
 *   node scripts/gen-radars.mjs
 * Fails loudly on shape drift so types never lie.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(scriptDir, '..');
const srcPath = resolve(appRoot, '..', 'preview', 'data', 'radars.json');
const outPath = resolve(appRoot, 'src', 'data', 'radars.ts');

const ALLOWED_ZONE_KEYS = new Set([
  'id', 'type', 'name', 'nameEn', 'geo', 'limit', 'operator', 'verified',
  'source', 'added', 'notes', 'corridor', 'lenM',
]);
const ALLOWED_CAM_KEYS = new Set([
  'id', 'type', 'name', 'nameEn', 'geo', 'limit', 'operator', 'verified',
  'source', 'added', 'notes', 'evidence', 'confidence', 'corridor', 'lenM',
]);
const TYPES = new Set(['fixed', 'avg', 'light', 'locality', 'bump']);

function isPair(v) {
  return Array.isArray(v) && v.length === 2 && v.every((n) => Number.isFinite(n));
}

function fail(msg) {
  console.error(`gen-radars: FAIL — ${msg}`);
  process.exit(1);
}

let raw;
try {
  raw = JSON.parse(readFileSync(srcPath, 'utf8'));
} catch (e) {
  fail(`cannot parse ${srcPath}: ${String(e)}`);
}

if (!raw.meta || !Array.isArray(raw.zones) || !Array.isArray(raw.cameras)) fail('missing meta/zones/cameras');
if (raw.zones.length + raw.cameras.length === 0) fail('empty corpus — refusing to emit');

for (const z of raw.zones) {
  const bad = Object.keys(z).filter((k) => !ALLOWED_ZONE_KEYS.has(k));
  if (bad.length) fail(`zone ${z.id} has keys outside CorpusZone: ${bad.join(', ')} (extend the type, not this script)`);
  if (!TYPES.has(z.type)) fail(`zone ${z.id} unknown type ${z.type}`);
  if (!isPair(z.geo)) fail(`zone ${z.id} geo not [lat,lng]`);
  if (z.corridor && (!isPair(z.corridor.enter) || !isPair(z.corridor.exit))) fail(`zone ${z.id} corridor pair`);
  if (z.lenM !== undefined && !Number.isFinite(z.lenM)) fail(`zone ${z.id} lenM`);
}

for (const c of raw.cameras) {
  const bad = Object.keys(c).filter((k) => !ALLOWED_CAM_KEYS.has(k));
  if (bad.length) fail(`camera ${c.id} has keys outside CorpusCamera: ${bad.join(', ')}`);
  if (!TYPES.has(c.type)) fail(`camera ${c.id} unknown type ${c.type}`);
  if (!isPair(c.geo)) fail(`camera ${c.id} geo not [lat,lng]`);
  if (c.limit !== null && !Number.isFinite(c.limit)) fail(`camera ${c.id} limit`);
  if (c.confidence !== undefined && typeof c.confidence !== 'number') fail(`camera ${c.id} confidence`);
  if (c.corridor && (!isPair(c.corridor.enter) || !isPair(c.corridor.exit))) fail(`camera ${c.id} corridor pair`);
  if (c.lenM !== undefined && !Number.isFinite(c.lenM)) fail(`camera ${c.id} lenM`);
}

// Re-serialize deterministically (stable key order), once, from the parsed object.
const json = JSON.stringify(raw, null, 2);
const indented = json.split('\n').map((line, i) => (i === 0 ? line : '  ' + line)).join('\n');

const banner = [
  '/**',
  ' * AUTO-GENERATED by scripts/gen-radars.mjs — do not hand-edit.',
  ` * Source: preview/data/radars.json (read-only corpus; regenerated ${raw.meta.generated}).`,
  ` * Zones: ${raw.zones.length} · Cameras: ${raw.cameras.length} · Sources: ${raw.meta.sources.join(' | ')}`,
  ' * Static bundle copy: offline-first, no server claim.',
  ' */',
].join('\n');

const body = `import type { RadarDataset } from '../types/radar';\n\n${banner}\nexport const RADAR_DATASET: RadarDataset = ${indented};\n`;

writeFileSync(outPath, body, 'utf8');
console.log(`gen-radars: wrote ${outPath} (zones=${raw.zones.length}, cameras=${raw.cameras.length})`);
